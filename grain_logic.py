        new_yeast = input(f"Дрожжи (текущие: {recipe['дрожжи']}): ").strip()
        if new_yeast:
            recipe['дрожжи'] = new_yeast
        
        # 4. Температура брожения
        new_temp = input(f"Температура брожения (текущая: {recipe['температура']}°C): ").strip()
        if new_temp:
            try:
                recipe['температура'] = float(new_temp)
            except ValueError:
                print("Оставлено прежнее значение (некорректный ввод).")
        
        # 5. Время брожения
        new_time = input(f"Время брожения (текущее: {recipe['время_брожения']}): ").strip()
        if new_time:
            recipe['время_брожения'] = new_time
        
        # 6. Описание
        new_desc = input(f"Описание (текущее: {recipe['описание']}): ").strip()
        if new_desc:
            recipe['описание'] = new_desc
        
        # 7. Сложность
        new_diff = input(f"Сложность (текущая: {recipe['сложность']}): ").strip()
        if new_diff:
            recipe['сложность'] = new_diff
        
        # 8. Выход
        new_yield = input(f"Выход (текущий: {recipe['выход']}): ").strip()
        if new_yield:
            recipe['выход'] = new_yield
        
        # === АВТОМАТИЧЕСКИЙ РАСЧЁТ ФЕРМЕНТОВ И ДРОЖЖЕЙ ===
        print("\n🔬 Автоматический расчёт на основе нового состава:")
        total_grain = sum(recipe['зерно'].values())
        water_volume = self.calculate_water_volume(recipe)
        
        if recipe.get('ферменты') is not None:
            enzymes = self.calculate_enzymes(recipe['зерно'])
