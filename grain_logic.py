    def add_custom_recipe(self):
        """Добавление нового пользовательского рецепта."""
        print("\n➕ ДОБАВЛЕНИЕ НОВОГО РЕЦЕПТА")
        print("Введите данные нового рецепта (пустые значения можно пропускать).")
        
        recipe = {}
        recipe['название'] = input("Название рецепта: ").strip()
        if not recipe['название']:
            print("❌ Название обязательно.")
            return
        
        # Зерновой состав
        recipe['зерно'] = {}
        print("Введите состав зерна (тип и количество, пустой тип - завершить):")
        while True:
            grain = input("  Тип зерна: ").strip().lower()
            if not grain:
                break
            try:
                amount = float(input(f"  Количество {grain} (кг): "))
                recipe['зерно'][grain] = amount
            except ValueError:
                print("  Некорректное количество, зерно пропущено.")
        
        if not recipe['зерно']:
            print("❌ Состав зерна обязателен.")
            return
        
        recipe['гидромодуль'] = input("Гидромодуль (например 1:4): ").strip() or "1:4"
        recipe['дрожжи'] = input("Тип дрожжей: ").strip() or "спиртовые"
        try:
            recipe['температура'] = float(input("Температура брожения (°C): ") or 25)
        except ValueError:
            recipe['температура'] = 25
        recipe['время_брожения'] = input("Время брожения (например 5-7 дней): ").strip() or "5-7 дней"
        recipe['описание'] = input("Описание: ").strip()
        recipe['сложность'] = input("Сложность (лёгкая/средняя/высокая): ").strip() or "средняя"
        recipe['выход'] = input("Ожидаемый выход (например 10 л АС): ").strip() or "неизвестно"
        
        # Ферменты
        use_enzymes = input("Используются ли ферменты? (да/нет, по умолчанию да): ").strip().lower()
        if use_enzymes in ['нет', 'no', 'n']:
            recipe['ферменты'] = None
        else:
            auto_enzymes = input("Рассчитать ферменты автоматически? (да/нет): ").strip().lower()
            if auto_enzymes == "да":
                recipe['ферменты'] = self.calculate_enzymes(recipe['зерно'])
            else:
                ферменты = {}
                print("Введите ферменты (название и количество, пустое название - завершить):")
                while True:
                    name = input("  Название фермента: ").strip()
                    if not name:
                        break
                    try:
                        amount = float(input(f"  Количество {name} (г): "))
                        ферменты[name] = amount
                    except ValueError:
                        print("  Некорректное количество, пропущено.")
                recipe['ферменты'] = ферменты if ферменты else None
        
        # Паузы
        recipe['паузы'] = []
        print("Температурные паузы (введите описание, пустая строка - завершить):")
        while True:
            pause = input("  Пауза: ").strip()
            if not pause:
                break
            recipe['паузы'].append(pause)
        
        recipe['перегон'] = input("Описание перегонки: ").strip()
        recipe['настаивание'] = input("Рекомендации по настаиванию: ").strip()
        recipe['примечания'] = input("Примечания: ").strip()
        
        self.custom_recipes.append(recipe)
        self._save_custom_recipes()
        print(f"✅ Рецепт «{recipe['название']}» добавлен в пользовательские.")
    
