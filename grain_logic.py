    def ask(self, question: str) -> str:
        question_lower = question.lower()
        best_match = None
        best_score = 0
        for entry in self.knowledge:
            score = 0
            for keyword in entry["ключевые_слова"]:
                if keyword.lower() in question_lower:
                    score += 1
            if score > best_score:
                best_score = score
                best_match = entry
        if best_match:
            return best_match["ответ"]
        else:
            return None


