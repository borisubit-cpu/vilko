    # ==================== ЗАГРУЗКА ДАННЫХ ИЗ JSON ====================
    def _load_json_or_default(self, filename, default_func):
        path = os.path.join(os.getcwd(), filename)
        if os.path.exists(path):
            try:
                with open(path, 'r', encoding='utf-8') as f:
                    return json.load(f)
            except (json.JSONDecodeError, IOError):
                pass
        
        data = default_func()
        try:
            with open(path, 'w', encoding='utf-8') as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
        except IOError:
            print(f"⚠️ Не удалось создать файл {filename}, данные будут только в памяти")
        return data
    
    # ==================== ВСПОМОГАТЕЛЬНЫЕ МЕТОДЫ ====================
    def calculate_water_volume(self, recipe: Dict) -> float:
        """Рассчитывает объём воды на основе состава зерна и гидромодуля."""
        try:
            total_grain = sum(recipe['зерно'].values())
            ratio_part = recipe['гидромодуль'].split(':')[1]
            ratio = float(ratio_part)  # поддерживает дробные значения (например, 4.5)
            return total_grain * ratio
        except:
            return 0.0
    
    def edit_recipe_interactive(self, recipe: Dict) -> Dict:
        """Позволяет пользователю изменить выбранный рецепт перед генерацией плана"""
        print("\n✏️ РЕДАКТИРОВАНИЕ РЕЦЕПТА")
        print("Оставьте поле пустым (нажмите Enter), чтобы сохранить текущее значение.")
        
        # 1. Зерновой состав
        print("\nТекущий состав зерна:")
        for grain, amount in recipe['зерно'].items():
            print(f"  {grain}: {amount} кг")
        
        change_grain = input("Хотите изменить состав зерна? (да/нет): ").lower()
        if change_grain == "да":
            new_grain_bill = {}
            while True:
                grain = input("Введите тип зерна (или 'готово' для завершения): ").strip().lower()
                if grain == "готово":
                    break
                if not grain:
                    continue
                amount = float(input(f"Количество {grain} (кг): "))
                new_grain_bill[grain] = amount
            if new_grain_bill:
                recipe['зерно'] = new_grain_bill
                # После изменения состава зерна выводим текущий расчёт воды
                total_grain = sum(recipe['зерно'].values())
                water = self.calculate_water_volume(recipe)
                print(f"Текущий состав зерна: {total_grain} кг, расчёт воды при гидромодуле {recipe['гидромодуль']}: {water} л")
        
        # 2. Гидромодуль
        new_hydro = input(f"Гидромодуль (текущий: {recipe['гидромодуль']}): ").strip()
        if new_hydro:
            recipe['гидромодуль'] = new_hydro
            # Сразу показываем расчёт воды
            total_grain = sum(recipe['зерно'].values())
            water = self.calculate_water_volume(recipe)
            print(f"Для {total_grain} кг зерна и гидромодуля {recipe['гидромодуль']} требуется {water} л воды.")
        else:
            # Если гидромодуль не менялся, всё равно выводим итоговый расчёт (на случай изменения состава зерна ранее)
            total_grain = sum(recipe['зерно'].values())
            water = self.calculate_water_volume(recipe)
            print(f"Итоговый расчёт: {total_grain} кг зерна, гидромодуль {recipe['гидромодуль']} -> {water} л воды.")
        
        # Остальные поля
        new_yeast = input(f"Дрожжи (текущие: {recipe['дрожжи']}): ").strip()
        if new_yeast:
            recipe['дрожжи'] = new_yeast
        
        new_temp = input(f"Температура брожения (текущая: {recipe['температура']}°C): ").strip()
        if new_temp:
            try:
                recipe['температура'] = float(new_temp)
            except ValueError:
                print("Оставлено прежнее значение (некорректный ввод).")
        
        new_time = input(f"Время брожения (текущее: {recipe['время_брожения']}): ").strip()
        if new_time:
            recipe['время_брожения'] = new_time
        
        new_desc = input(f"Описание (текущее: {recipe['описание']}): ").strip()
        if new_desc:
            recipe['описание'] = new_desc
        
        new_diff = input(f"Сложность (текущая: {recipe['сложность']}): ").strip()
        if new_diff:
            recipe['сложность'] = new_diff
        
        new_yield = input(f"Выход (текущий: {recipe['выход']}): ").strip()
        if new_yield:
            recipe['выход'] = new_yield
        
        return recipe
    
