    def generate_plan(self, recipe: Dict) -> List[Dict]:
        """Создаёт план на основе переданного словаря рецепта"""
        plan = []
        day = 1
        
        # Этап 1: Подготовка зерна
        grain_str = ', '.join([f'{v} кг {k}' for k, v in recipe['зерно'].items()])
        plan.append({
            "день": day,
            "этап": "Подготовка",
            "действие": f"Подготовить сырьё: {grain_str}",
            "время": "30 минут"
        })
        plan.append({
            "день": day,
            "этап": "Подготовка",
            "действие": "Промыть, при необходимости замочить",
            "время": "4-6 часов"
        })
        plan.append({
            "день": day,
            "этап": "Подготовка",
            "действие": "Измельчить зерно (крупный помол)",
            "время": "1 час"
        })
        
        # Этап 2: Затирание и осахаривание
        water_volume = self.calculate_water_volume(recipe)
        if water_volume <= 0:
            water_volume = 100  # на случай нестандартного гидромодуля
        
        plan.append({
            "день": day + 1,
            "этап": "Затирание",
            "действие": f"Нагреть {water_volume:.1f} л воды до требуемой температуры",
            "время": "30-40 минут"
        })
        plan.append({
            "день": day + 1,
            "этап": "Затирание",
            "действие": "Внести зерно, перемешать",
            "время": "15 минут"
        })
        # Добавляем паузы из рецепта
        for pause in recipe.get("паузы", []):
            plan.append({
                "день": day + 1,
                "этап": "Осахаривание",
                "действие": pause,
                "время": "указано в описании паузы"
            })
        
        # Этап 3: Брожение
        days_fermentation = int(recipe["время_брожения"].split("-")[-1].split()[0])
        plan.append({
            "день": day + 2,
            "этап": "Брожение",
            "действие": f"Охладить сусло до {recipe['температура']}°C",
            "время": "1-2 часа"
        })
        plan.append({
            "день": day + 2,
            "этап": "Брожение",
            "действие": f"Внести дрожжи: {recipe['дрожжи']}, установить гидрозатвор",
            "время": "30 минут"
        })
        plan.append({
            "день": f"{day + 2} - {day + 2 + days_fermentation}",
            "этап": "Брожение",
            "действие": f"Брожение при {recipe['температура']}°C, ежедневно перемешивать",
            "время": recipe["время_брожения"]
        })
        
        # Этап 4: Перегонка
        plan.append({
            "день": day + 2 + days_fermentation,
            "этап": "Первая перегонка",
            "действие": "Первая перегонка до 0° крепости в струе",
            "время": "3-4 часа"
        })
        plan.append({
            "день": day + 3 + days_fermentation,
            "этап": "Вторая перегонка",
            "действие": "Вторая дробная перегонка с отбором голов (5-10%)",
            "время": "4-5 часов"
        })
        plan.append({
            "день": day + 4 + days_fermentation,
            "этап": "Финализация",
            "действие": "Разбавить до нужной крепости, при необходимости заложить щепу, дать отдохнуть",
            "время": "по рецепту"
        })
        
        self.current_plan = plan
        return plan
    
