    def calculate_yield(self, grain_type: str, amount_kg: float) -> float:
        """Расчёт ожидаемого выхода абсолютного спирта (л АС) из количества
        зерна на основе коэффициента 'выход_спирта' из базы зерна."""
        if amount_kg is None or amount_kg <= 0:
            raise ValueError("Количество зерна должно быть больше нуля")
        grain = self.grain_base.get(grain_type)
        if grain is None:
            raise ValueError(f"Неизвестный тип зерна: {grain_type}")
        coefficient = grain.get('выход_спирта', 0)
        return amount_kg * coefficient

    def calculate_water_volume(self, recipe: Dict) -> float:
        try:
            total_grain = sum(recipe['зерно'].values())
            ratio_part = recipe['гидромодуль'].split(':')[1]
            ratio = float(ratio_part)
            return total_grain * ratio
        except:
            return 0.0
    
    def calculate_enzymes(self, grain_bill: Dict) -> Dict:
        norms = {
            'Амилосубтилин': 0.5,
            'Глюкаваморин': 1.0,
            'Протосубтилин': 0.2
        }
        total_grain = sum(grain_bill.values())
        return {name: round(norm * total_grain, 1) for name, norm in norms.items()}
    
    def calculate_yeast(self, water_volume: float, yeast_type: str) -> float:
        yeast_norms = {
            'спиртовые': 0.4,
            'турбо': 0.6,
            'винные': 0.5,
            'пивные': 0.5,
            'SafSpirit M-1': 0.5,
            'SafSpirit USW-6': 0.5,
            'пивные (Safale S-04)': 0.5,
            'спиртовые (для бурбона)': 0.5,
            'винные (совиньон)': 0.5,
            'винные (красные)': 0.5
        }
        norm = yeast_norms.get(yeast_type, 0.5)
        return round(water_volume * norm, 1)
    
